--
-- 1. CRIAÇÃO DAS TABELAS
--
-- Tabela Principal de Funcionários
CREATE TABLE funcionarios (
    id NUMBER PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    cargo VARCHAR2(50),
    salario NUMBER(10, 2) NOT NULL,
    data_cadastro DATE DEFAULT SYSDATE
);

-- Tabela de Auditoria / Log de Salários
CREATE TABLE log_salarios (
    id_log NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcionario NUMBER NOT NULL,
    salario_antigo NUMBER(10, 2),
    salario_novo NUMBER(10, 2),
    data_alteracao DATE DEFAULT SYSDATE,
    usuario VARCHAR2(50)
);

-- After Update
-- Este trigger é executado automaticamente SEMPRE que o campo 'salario'
-- de qualquer funcionário for modificado.

CREATE OR REPLACE TRIGGER trg_audita_salario
AFTER UPDATE OF salario ON funcionarios
FOR EACH ROW
BEGIN
    INSERT INTO log_salarios (
        id_funcionario,
        salario_antigo,
        salario_novo,
        data_alteracao,
        usuario
    ) VALUES (
        :OLD.id,
        :OLD.salario,
        :NEW.salario,
        SYSDATE,
        USER
    );
END;
/

--
-- 3. 
-- 
-- Este trigger garante que o nome do funcionário seja sempre salvo em MAIÚSCULO
-- antes de gravar no banco de dados.

CREATE OR REPLACE TRIGGER trg_formata_nome_func
BEFORE INSERT OR UPDATE OF nome ON funcionarios
FOR EACH ROW
BEGIN
    :NEW.nome := UPPER(TRIM(:NEW.nome));
END;
/

